import assert from 'node:assert/strict';
import { createWorkerDrainController } from '../playwright-worker/src/worker-drain.js';
const drain = createWorkerDrainController();
assert.equal(drain.snapshot().status, 'WORKER_ACTIVE');
const first = drain.beginOperation();
const second = drain.beginOperation();
assert.equal(drain.snapshot().activeOperations, 2);
const pending = drain.drain();
assert.equal(pending.drained, false);
assert.equal(pending.status, 'WORKER_DRAINING');
assert.equal(drain.beginOperation(), null, 'New operations must be rejected once drain starts');
first();
first();
assert.equal(drain.snapshot().activeOperations, 1, 'release must be idempotent');
second();
assert.equal(drain.snapshot().status, 'WORKER_DRAINED');
assert.equal(drain.snapshot().activeOperations, 0);
assert.equal(drain.beginOperation(), null);
drain.resume();
assert.equal(drain.snapshot().status, 'WORKER_ACTIVE');
const third = drain.beginOperation();
assert.equal(drain.snapshot().activeOperations, 1);
third();
assert.equal(drain.snapshot().activeOperations, 0);
console.log('Worker drain state machine regression passed.');
